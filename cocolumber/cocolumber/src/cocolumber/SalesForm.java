    // Load all sales data from database into JTable
    private void loadSalesTable() {
        DefaultTableModel model = (DefaultTableModel) tblSales.getModel();
        model.setRowCount(0); // clear existing rows

        try {
            Connection conn = DBConnection.connect(); // make sure your DBConnection class is correct
            String sql = "SELECT sale_id, sale_datetime, total_amount, staff_id FROM sales";
            Statement stmt = conn.createStatement();
            ResultSet rs = stmt.executeQuery(sql);

            while (rs.next()) {
                Object[] row = {
                    rs.getInt("sale_id"),
                    rs.getString("sale_datetime"),
                    rs.getDouble("total_amount"),
                    rs.getInt("staff_id")
                };
                model.addRow(row);
            }

            conn.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error loading sales: " + e.getMessage());
        }
    }

    private void btnCalculateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalculateActionPerformed
        try {
            int productId = Integer.parseInt(txtProductID.getText());
            int quantity = Integer.parseInt(txtQuantity.getText());

            Connection conn = DBConnection.connect();
            PreparedStatement pst = conn.prepareStatement("SELECT unit_price FROM product WHERE product_id = ?");
            pst.setInt(1, productId);
            ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                double unit_price = rs.getDouble("unit_price");
                double total = unit_price * quantity;
                txtTotalPrice.setText(String.valueOf(total));
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Product not found!");
            }

            conn.close();
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter valid numbers for Product ID and Quantity.");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }           // TODO add your handling code here:
    }//GEN-LAST:event_btnCalculateActionPerformed

