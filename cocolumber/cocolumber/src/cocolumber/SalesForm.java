    private void btnAddSaleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddSaleActionPerformed
        try {
            int productId = Integer.parseInt(txtProductID.getText());
            int quantity = Integer.parseInt(txtQuantity.getText());
            double total = Double.parseDouble(txtTotalPrice.getText());

            Connection conn = DBConnection.connect();

            // Step 1: Insert main sale record
            String sqlSale = "INSERT INTO sales (sale_datetime, total_amount) VALUES (NOW(), ?)";
            PreparedStatement pstSale = conn.prepareStatement(sqlSale, Statement.RETURN_GENERATED_KEYS);
            pstSale.setDouble(1, total);
            pstSale.executeUpdate();

            // Step 2: Get the generated sale_id
            ResultSet rs = pstSale.getGeneratedKeys();
            int saleId = 0;
            if (rs.next()) {
                saleId = rs.getInt(1);
            }

            // Step 3: Insert sale item (this is where your new code goes)
            String sqlItem = "INSERT INTO sale_item (sale_id, product_id, quantity, unit_price, subtotal) VALUES (?, ?, ?, ?, ?)";
            PreparedStatement pstItem = conn.prepareStatement(sqlItem);
            pstItem.setInt(1, saleId);
            pstItem.setInt(2, productId);
            pstItem.setInt(3, quantity);

            // 🧮 Calculate unit price
            double unitPrice = total / quantity;

            pstItem.setDouble(4, unitPrice);  // unit_price column
            pstItem.setDouble(5, total);      // subtotal column
            pstItem.executeUpdate();

            String sqlUpdateStock = "UPDATE product SET stock_quantity = stock_quantity - ? WHERE product_id = ?";
            PreparedStatement pstUpdate = conn.prepareStatement(sqlUpdateStock);
            pstUpdate.setInt(1, quantity);
            pstUpdate.setInt(2, productId);
            pstUpdate.executeUpdate();

            javax.swing.JOptionPane.showMessageDialog(this, "Sale added successfully!");
            conn.close();

            loadSalesTable(); // refresh table

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please calculate total first or enter valid values.");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error adding sale: " + e.getMessage());
        }
    }//GEN-LAST:event_btnAddSaleActionPerformed

