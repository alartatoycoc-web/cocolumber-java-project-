    private void loadStaff() {
        try {
            conn = DBConnection.connect();
            String sql = "SELECT staff_id, name, role, username FROM staff";
            pstmt = conn.prepareStatement(sql);
            rs = pstmt.executeQuery();

            javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblStaff.getModel();
            model.setRowCount(0); // clear existing rows

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getInt("staff_id"),
                    rs.getString("name"),
                    rs.getString("role"),
                    rs.getString("username")
                });
            }

            conn.close();
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error loading staff: " + e.getMessage());
        }
    }

