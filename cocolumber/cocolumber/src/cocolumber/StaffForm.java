    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        try {
            conn = DBConnection.connect();
            String sql = "INSERT INTO staff (admin_id, name, role, username, password) VALUES (?, ?, ?, ?, ?)";
            pstmt = conn.prepareStatement(sql);

            pstmt.setInt(1, 1); // assuming admin_id = 1 (you can change)
            pstmt.setString(2, txtName.getText());
            pstmt.setString(3, txtRole.getText());
            pstmt.setString(4, txtUsername.getText());
            pstmt.setString(5, new String(txtPassword.getPassword()));

            pstmt.executeUpdate();
            javax.swing.JOptionPane.showMessageDialog(this, "Staff Added Successfully!");
            conn.close();
            loadStaff();
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error adding staff: " + e.getMessage());
        }        // TODO add your handling code here:
    }//GEN-LAST:event_btnAddActionPerformed

    private void tblStaffMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblStaffMouseClicked
        int row = tblStaff.getSelectedRow();
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblStaff.getModel();

        txtStaffID.setText(model.getValueAt(row, 0).toString());
        txtName.setText(model.getValueAt(row, 1).toString());
        txtRole.setText(model.getValueAt(row, 2).toString());
        txtUsername.setText(model.getValueAt(row, 3).toString());        // TODO add your handling code here:
    }//GEN-LAST:event_tblStaffMouseClicked

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        try {
            conn = DBConnection.connect();
            String sql = "UPDATE staff SET name=?, role=?, username=?, password=? WHERE staff_id=?";
            pstmt = conn.prepareStatement(sql);

            pstmt.setString(1, txtName.getText());
            pstmt.setString(2, txtRole.getText());
            pstmt.setString(3, txtUsername.getText());
            pstmt.setString(4, new String(txtPassword.getPassword()));
            pstmt.setInt(5, Integer.parseInt(txtStaffID.getText()));

            pstmt.executeUpdate();
            javax.swing.JOptionPane.showMessageDialog(this, "Staff updated successfully!");
            conn.close();
            loadStaff();
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error updating staff: " + e.getMessage());
        }        // TODO add your handling code here:
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        try {
            int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this staff?", "Confirm Delete", javax.swing.JOptionPane.YES_NO_OPTION);
            if (confirm == javax.swing.JOptionPane.YES_OPTION) {
                conn = DBConnection.connect();
                String sql = "DELETE FROM staff WHERE staff_id=?";
                pstmt = conn.prepareStatement(sql);
                pstmt.setInt(1, Integer.parseInt(txtStaffID.getText()));
                pstmt.executeUpdate();
                javax.swing.JOptionPane.showMessageDialog(this, "Staff deleted successfully!");
                conn.close();
                loadStaff();
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error deleting staff: " + e.getMessage());
        }        // TODO add your handling code here:
    }//GEN-LAST:event_btnDeleteActionPerformed

